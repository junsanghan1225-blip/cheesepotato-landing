/* TOPIK 듣기 유형 연습.
   배우기 › TOPIK 유형 연습 › 듣기 가 읽는다.

   **기출이 아니다.** 국립국제교육원과 무관한 자체 제작 문항이고 유형만
   따라 했다. 대본·발문·선택지는 전부 새로 쓴 것이어야 한다. 기출 대본을
   옮겨 오지 마라 — 저작권 침해이고, 화면에 「연습문제」라 적어 둔 것이
   거짓이 된다.

   id 는 한 번 정하면 안 바꾼다. 진도가 이 id 로 묶인다.

   ── 소리를 어떻게 내는가 ─────────────────────────────
   한 문항 = 한 MP3 다. assets/audio/listen/<id>.mp3 를 먼저 찾고, 없으면
   브라우저 내장 목소리가 script 를 차례로 읽는다. app.module.js 의 say()
   와 같은 폴백이라 **파일을 채우면 코드를 안 고쳐도 바뀐다.**

   줄마다 파일을 따로 두지 않는 이유 — 실제 시험은 대화가 끊기지 않고
   이어서 들린다. 줄 사이에 로딩 틈이 생기면 난이도가 달라진다.

   ── who 를 반드시 갈라라 ────────────────────────────
   듣기 문항의 절반이 「여자는 무엇을 합니까」다. 남녀가 같은 목소리로
   나오면 그 문제는 풀 수가 없다. 소리를 구울 때 남·여를 다른 목소리로
   내고 이어 붙여야 한다 (tools/listen-script.mjs 가 갈라서 뽑아 준다).

   ── 밭 ──────────────────────────────────────────────
   slot    흉내 내는 실제 시험의 문항 번호.
   script  들려줄 대화. [{ who:'m'|'w'|'n', text }]
           n 은 안내 방송·독백처럼 화자가 대화 상대가 아닌 자리.
   q       화면에 보이는 발문.
   answer  0부터 센다. 정답 자리는 넷에 고루 흩어라 — 몰리면 학습자가
           내용 대신 자리를 외운다. tools/check-listening.mjs 가 잡는다.
   pair    한 대본에 두 문제가 붙는 자리(긴 담화)에서 짝을 묶는 이름.
           두 문항의 script 가 글자까지 같아야 한다.

   해설(why)에서 보기를 번호로 가리키지 마라. 보기 순서는 정답 자리를
   고르게 맞추느라 바뀌고, 그때 번호만 남으면 해설이 엉뚱한 보기를
   가리키게 된다. 보기 글자를 그대로 인용한다. */

