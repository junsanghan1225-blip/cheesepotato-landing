/* 지문에서 누른 꼴 → 사전의 표제어.
 *
 * 사전은 「먹다」로 적혀 있고 지문에는 「먹었습니다」로 나온다. 학습자가 누르는
 * 것은 언제나 지문 쪽이다. 그래서 처음 붙여 놓고 재 보니 **눌러서 뜻이 따라온
 * 것이 열에 넷**이었다 — 사전에 5천 낱말이 들어 있는데도 그랬다.
 *
 * 못 찾은 것을 자주 나오는 차례로 늘어놓으니 거의 다 두 갈래였다.
 *
 *   저는 · 씨는 · 것이 · 집에서 · 문을 · 비가      ← 이름씨 + 토씨
 *   않았습니다 · 가지고 · 싶습니다 · 어릴 · 있었다  ← 풀이씨의 활용
 *
 * 둘 다 **뒤만 떼면** 사전에 있는 꼴이 된다. 여기서 그 일을 한다.
 *
 * ── 틀린 뜻을 내주느니 빈 칸을 내준다 ────────────────────────
 * 뒤를 떼는 일은 잘못하면 엉뚱한 말을 집는다. 「가지고」의 앞 한 자만 떼면
 * 「가다」가 되어 버린다 — 학습자는 그 틀린 뜻을 그대로 외운다.
 *
 * 그래서 규칙을 둘 두었다.
 *
 *   1. **떼어 낸 결과가 사전에 실제로 있을 때만** 인정한다. 지어내지 않는다.
 *   2. **덜 뗀 것이 이긴다.** 「가지고」는 「가지다」에서 멈추지 「가다」까지
 *      가지 않는다. 그리고 안 떼고 그대로 맞는 것이 늘 먼저다.
 *
 * 떼어도 되는 꼬리도 미리 적어 둔 글자로 막아 둔다. 아무 데서나 자르면
 * 「민수」가 「민다」가 된다 — 사람 이름이 동사로 담기는 것이다.
 */

/* 이름씨 뒤에 붙는 토씨. 긴 것부터 본다 — 「에서」를 「에」로 먼저 자르면
   「집에서」가 「집에」가 되어 또 못 찾는다. */
const JOSA = [
  '이라고', '이라는', '에서는', '에서도', '에게서', '에게는', '에게도', '한테는',
  '으로는', '으로도', '까지는', '부터는', '만큼은', '에는', '에도', '에만', '와는',
  '과는', '로는', '로도', '라고', '라는', '까지', '부터',
  '에서', '에게', '한테', '으로', '보다', '처럼', '만큼', '조차', '밖에', '마다',
  '대로', '이나', '이란', '이든', '이랑', '이며', '라도', '에다', '께서',
  /* 잡음씨 「이다」도 여기서 함께 뗀다. 「것입니다」의 「것」을 못 찾는 것은
     토씨를 못 뗀 것과 똑같은 일이다. */
  '이었습니다', '이었다', '였습니다', '입니다', '입니까', '이에요', '예요',
  '이다', '이야', '이라', '이고',
  '는', '은', '이', '가', '을', '를', '에', '와', '과', '로', '도', '만', '의',
  '나', '란', '든', '랑', '며', '께', '야',
].sort((a, b) => b.length - a.length);

/* 풀이씨의 꼬리에 쓰이는 글자. 여기 있는 글자로만 이루어진 꼬리라야 뗀다.
   「민수」의 「수」, 「지현」의 「현」이 여기 없어서 사람 이름은 안 잘린다. */
const TAIL = new Set([
  '습', '니', '다', '았', '았', '었', '였', '겠', '고', '며', '면', '서', '아', '어',
  '여', '자', '지', '네', '는', '은', '을', '기', '게', '도', '록', '더', '라', '까',
  '나', '요', '죠', '시', '셨', '세', '셔', '십', '읍', '던', '든', '대', '단', '답',
  '냐', '데', '텐', '려', '러', '므', '로', '야', '군', '음', '임', '만', '으',
]);

/* ── 한글 낱자 셈 ────────────────────────────────────────────
   「어릴」의 ㄹ 을 떼어 「어리」를 얻고, 「해」를 「하」로 되돌리는 데 쓴다.
   글자 안을 들여다보지 않으면 이 둘은 못 찾는다 — 앞에서부터 자르는 것만으로는
   「어릴」이 「어」밖에 안 남는다. */
const BASE = 0xac00;
const has = (ch) => { const n = ch.charCodeAt(0) - BASE; return n >= 0 && n < 11172; };
const parts = (ch) => { const n = ch.charCodeAt(0) - BASE; return [Math.floor(n / 588), Math.floor((n % 588) / 28), n % 28]; };
const build = (c, v, t) => String.fromCharCode(BASE + c * 588 + v * 28 + t);

/* 어미로 붙는 받침. 「어릴」의 ㄹ, 「간다」의 ㄴ, 「봤다」의 ㅆ.
   ㄱ·ㅅ 따위는 안 뗀다 — 「먹」에서 ㄱ 을 떼면 「머」가 되어 딴말이 된다. */
const JONG_END = new Set([4 /* ㄴ */, 8 /* ㄹ */, 16 /* ㅁ */, 17 /* ㅂ */, 20 /* ㅆ */]);

/* 줄어든 홀소리를 되돌린다. 「해」→「하」, 「봐」→「보」, 「줘」→「주」,
   「돼」→「되」, 「가르쳐」→「가르치」. */
const VOWEL = new Map([[9, 8] /* ㅘ→ㅗ */, [14, 13] /* ㅝ→ㅜ */, [10, 11] /* ㅙ→ㅚ */,
                       [1, 0] /* ㅐ→ㅏ */, [6, 20] /* ㅕ→ㅣ */, [5, 20] /* ㅔ→ㅣ */]);

/* 받침 ㅎ 을 도로 붙인 꼴. 「빨간」은 받침을 떼면 「빨가」인데 그런 말은
   없고 「빨갛다」가 있다 — ㅎ 불규칙이다. 「하얀」 「그런」 「어떤」이 다 이 꼴. */
const addH = (s) => {
  const last = s.slice(-1);
  if (!s || !has(last)) return '';
  const [c, v, t] = parts(last);
  return t === 0 ? s.slice(0, -1) + build(c, v, 27 /* ㅎ */) : '';
};

/* 마지막 글자의 받침만 떼어 낸 꼴. 뗄 것이 없으면 빈 문자열. */
function noJong(s) {
  const last = s.slice(-1);
  if (!s || !has(last)) return '';
  const [c, v, t] = parts(last);
  return JONG_END.has(t) ? s.slice(0, -1) + build(c, v, 0) : '';
}

/* 마지막 글자의 줄어든 홀소리를 되돌린 꼴. 되돌릴 것이 없으면 빈 문자열. */
function unTie(s) {
  const last = s.slice(-1);
  if (!s || !has(last)) return '';
  const [c, v, t] = parts(last);
  if (t !== 0 || !VOWEL.has(v)) return '';
  return s.slice(0, -1) + build(c, VOWEL.get(v), 0);
}

/**
 * 누른 꼴에 닿는 표제어를 찾는다. 없으면 빈 문자열.
 *
 * @param {(key: string) => boolean} inDict  그 꼴이 사전에 있는지 묻는다
 * @param {string} word                      지문에서 누른 꼴
 * @returns {string} 사전에 있는 표제어, 또는 ''
 */
export function glossFind(inDict, word) {
  const w = String(word || '');
  if (!w || w.length > 20) return '';

  /* 1. 그대로 있으면 그대로다. 어떤 떼기보다 먼저다 — 「사과」를 「사」로,
        「그리고」를 「그리다」로 만들지 않으려면 이 줄이 맨 앞이어야 한다. */
  if (inDict(w)) return w;

  /* 2. 토씨 떼기. 뗀 자리가 사전에 있을 때만 인정한다.
        떼고 나서 「들」이 남으면 그것도 뗀다 — 사전은 「사람」으로 적혀 있고
        지문에는 「사람들이」로 나온다. */
  const noDeul = (s) => (s.length > 2 && s.endsWith('들') ? s.slice(0, -1) : '');
  for (const j of ['', ...JOSA]) {
    if (j && (!w.endsWith(j) || w.length <= j.length)) continue;
    const stem = j ? w.slice(0, -j.length) : w;
    if (j && inDict(stem)) return stem;
    const one = noDeul(stem);
    if (one && inDict(one)) return one;
  }

  /* 3. 활용 되돌리기. 뒤에서부터 조금씩 떼며 「…다」를 붙여 본다.
        덜 뗀 쪽이 먼저다 — 「가지고」는 「가지다」에서 멈춘다. */
  for (let n = w.length; n >= 1; n--) {
    const tail = w.slice(n);
    /* 꼬리에 어미 아닌 글자가 섞였으면 거기서 자를 자리가 아니다. */
    if ([...tail].some((ch) => !TAIL.has(ch))) continue;
    const stem = w.slice(0, n);
    /* 「했다」의 「했」은 두 번 되돌려야 「하」가 된다 — 받침 ㅆ 을 떼어
       「해」로, 줄어든 ㅐ 를 펴서 「하」로. 한 번만 하면 「해다」에서 멈춘다. */
    for (const cand of [stem, noJong(stem), unTie(stem), unTie(noJong(stem)), addH(noJong(stem))]) {
      if (cand && inDict(cand + '다')) return cand + '다';
    }
  }

  return '';
}
