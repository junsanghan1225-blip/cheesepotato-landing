#!/usr/bin/env node
/* 발음 레벨 테스트 지문을 더 만들기 위한 지시문을 뽑는다.

   쓰기: node tools/pron-prompt.mjs easy
         node tools/pron-prompt.mjs normal
         node tools/pron-prompt.mjs hard

   단계마다 따로 뽑는 이유 — 한 번에 세 단계를 시키면 모델이 길이 기준을
   섞어 버린다. 실제로 그랬다. 한 판에 한 단계만 시키면 그 단계의 치수에만
   집중한다.

   지금 있는 지문을 지시문 안에 그대로 넣는다. 「이런 느낌으로」라고 말로
   설명하는 것보다 실물을 보여주는 쪽이 훨씬 잘 맞는다. 겸사겸사 겹치는
   지문도 덜 나온다. */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LV = (process.argv[2] || '').trim();

const src = fs.readFileSync(path.join(ROOT, 'app.js'), 'utf8');
const seg = src.slice(src.indexOf('const PT_SETS'), src.indexOf('const PT_LV_NAME'));
const SETS = {};
for (const m of seg.matchAll(/(easy|normal|hard):\s*\[([\s\S]*?)\n\s*\],/g)) {
  SETS[m[1]] = [...m[2].matchAll(/'([^']*)'/g)].map((x) => x[1]);
}

const HOW_MANY = 50;

const 공통 = `너는 한국어 교재를 만드는 사람이다. 한국어를 배우는 외국인이
**소리 내어 읽을** 문장을 만든다. 이 문장은 학습자가 읽고, 브라우저의 음성
인식이 받아 적고, 원문과 자모 단위로 견주어 발음 점수를 낸다.

그래서 아래 규칙은 취향이 아니라 채점이 망가지느냐 마느냐의 문제다.

## 절대 규칙

1. **한글과 마침표·물음표·느낌표·쉼표 말고는 아무것도 쓰지 마라.**
   숫자(1, 2, 15), 로마자(TV, USB, OK), 괄호, 따옴표, 줄표, 이모지 전부 금지.
   왜냐면 인식기는 소리를 한글로 받아 적는다. 원문에 「15%」라고 적혀 있으면
   학습자가 아무리 정확하게 「십오 퍼센트」라고 읽어도 글자가 하나도 안 맞아
   0점이 된다. 발음을 재야 할 자리에서 표기법을 재게 된다.

2. **수는 「한 잔」「두 개」「세 번」 정도의 작은 수관형사까지만.**
   열 이상의 수, 날짜, 시각, 가격, 퍼센트는 쓰지 마라. 인식기가 「15」로 적을지
   「십오」로 적을지 제각각이라 같은 이유로 점수가 무너진다.

3. **인식기가 확실히 알아듣는 일상 낱말만 써라.**
   사람 이름·지명·상호·상표는 쓰지 마라(인식기가 엉뚱하게 적는다).
   문학적이거나 예스러운 낱말, 한자어 전문 용어도 피해라.
   완전히 굳은 외래어(커피, 버스, 지하철, 컴퓨터)는 괜찮지만 그 밖의 외래어는
   쓰지 마라.

4. **시사·정치·종교·질병·사고·돈 이야기는 쓰지 마라.** 날씨, 밥, 길, 계절,
   가족, 취미처럼 언제 읽어도 편안한 장면으로 채워라. 시간이 지나도 안 낡는
   내용이어야 한다.

5. **소리 내어 읽었을 때 자연스러워야 한다.** 눈으로만 읽는 글이 아니다.
   말이 꼬이거나 숨이 모자라는 문장은 안 된다.

6. 앞뒤 문장이 서로 이어지는 하나의 장면이어야 한다. 관계없는 두 문장을
   붙여 놓지 마라.`;

const 마무리 = (n) => `
## 내놓는 방법

JSON 배열 하나로만 답해라. 설명, 번호, 머리말, 코드펜스 밖의 말은 붙이지 마라.

\`\`\`json
[
  "첫 번째 지문",
  "두 번째 지문"
]
\`\`\`

정확히 **${n}개**를 담아라. 위에 보여 준 지문과 겹치면 안 되고, ${n}개끼리도
서로 겹치면 안 된다. 장면도 골고루 흩어라 — 같은 소재(예: 커피)가 세 번 넘게
나오지 않게 해라.`;

const PROMPT = {
  easy: () => `${공통}

## 이번에 만들 것 — 「쉬움」 단계 ${HOW_MANY}개

한국어를 갓 배우기 시작한 사람이 읽는다. 발음 규칙 때문에 막히면 안 되고,
글자 그대로 읽으면 거의 맞아떨어져야 한다.

* **한 문장.** 마침표는 끝에 딱 하나.
* **띄어쓰기까지 세어 10자 이상 16자 이하.** (지금 있는 것들은 10~14자다)
* **해요체로 끝낸다.** 「…요.」 로 끝나야 한다.
* **겹받침을 절대 쓰지 마라.** ㄳ ㄵ ㄶ ㄺ ㄻ ㄼ ㄽ ㄾ ㄿ ㅀ ㅄ 이 든 글자
  (값, 넋, 앉다, 읽다, 젊다, 밟다, 짧다, 싫다, 없다, 흙, 삶 …) 는 하나도 쓰지 마라.
  **「없어요」「있잖아요」 같은 흔한 말도 겹받침이라 안 된다.**
* **연음이 생기는 자리를 두 군데 이하로.** (많아야 세 군데)
  받침 있는 글자 바로 뒤에 ㅇ 으로 시작하는 글자가 오면 연음이다
  (밥을 → 바블, 물이 → 무리). 이게 많으면 글자와 소리가 달라져서
  초보가 헷갈린다.
* 받침은 홑받침만 쓰면 되고, 그 밖에는 평범한 일상 문장이면 된다.
  「학교」「같이」처럼 아주 흔한 말은 소리가 좀 달라져도(학꾜·가치)
  초보도 이미 통째로 아는 낱말이라 괜찮다. 다만 그런 자리를 한 문장에
  여러 개 몰아넣지는 마라.

지금 있는 「쉬움」 지문 ${SETS.easy.length}개 — 이 결과 그대로 이어 붙일 것이니
길이와 말맛을 여기에 맞춰라:

${SETS.easy.map((s) => `  ${s}`).join('\n')}
${마무리(HOW_MANY)}`,

  normal: () => `${공통}

## 이번에 만들 것 — 「보통」 단계 ${HOW_MANY}개

한국어를 얼마쯤 해 본 사람이 읽는다. 일상적인 두 문장짜리 장면이다.

* **정확히 두 문장.** 마침표(또는 물음표·느낌표)가 딱 두 개.
* **첫 문장은 「…습니다.」, 둘째 문장은 「…아요./…어요.」** 로 끝낸다.
  두 말투를 한 번에 연습시키려고 일부러 이렇게 짜 두었다. 반드시 지켜라.
* **띄어쓰기까지 세어 두 문장 합쳐 38자 이상 48자 이하.**
  (지금 있는 것들은 40~45자다)
* 겹받침은 있어도 되지만 한 지문에 **두 개까지만.** 여기는 겹받침을
  연습시키는 자리가 아니다.
* 받침과 연음이 자연스럽게 섞이되, 일부러 어렵게 만들지는 마라.

지금 있는 「보통」 지문 ${SETS.normal.length}개 — 길이와 짜임을 여기에 맞춰라:

${SETS.normal.map((s) => `  ${s}`).join('\n')}
${마무리(HOW_MANY)}`,

  hard: () => `${공통}

## 이번에 만들 것 — 「어려움」 단계 ${HOW_MANY}개

발음이 꽤 되는 사람의 실력을 가르는 자리다. **글자와 소리가 어긋나는 자리**를
일부러 여러 번 넣는다. 이게 이 단계의 존재 이유다.

* **정확히 두 문장.** 첫 문장 「…습니다.」, 둘째 문장 「…아요./…어요.」
* **띄어쓰기까지 세어 두 문장 합쳐 45자 이상 58자 이하.**
  (지금 있는 것들은 47~56자다)
* **겹받침이 한 지문에 적어도 하나, 될 수 있으면 둘에서 넷.**
  값, 넋, 삯, 몫, 맑은, 밝은, 읽던, 늙은, 앉은, 얹어, 젊은, 삶은, 밟고,
  훑어, 핥아, 짧은, 넓은, 싫증, 잃어, 없이, 얇은 …
* **아래 네 가지 가운데 적어도 두 가지를 한 지문 안에 넣어라.**
  1. 구개음화 — 굳이, 같이, 해돋이, 붙이다, 닫히다
  2. 경음화 — 학교, 낙지, 입고, 옷장, 밥그릇, 국밥
  3. ㅎ 약화·탈락 — 좋은, 많이, 싫어, 놓아, 쌓인
  4. ㄴ 첨가 — 색연필, 꽃잎, 나뭇잎, 담요, 한여름
* 그래도 **낱말은 일상어**여야 한다. 어렵게 만드는 건 발음이지 어휘가 아니다.
  어려운 낱말을 쓰면 인식기가 못 알아들어서, 잘 읽은 사람이 0점을 받는다.

지금 있는 「어려움」 지문 ${SETS.hard.length}개 — 이 밀도를 그대로 맞춰라:

${SETS.hard.map((s) => `  ${s}`).join('\n')}
${마무리(HOW_MANY)}`,
};

if (!PROMPT[LV]) {
  console.error('쓰기: node tools/pron-prompt.mjs easy|normal|hard');
  console.error('  easy   — 쉬움 (한 문장, 10~16자, 겹받침 없음)');
  console.error('  normal — 보통 (두 문장, 38~48자)');
  console.error('  hard   — 어려움 (두 문장, 45~58자, 겹받침·발음 규칙 여럿)');
  process.exit(1);
}
console.log(PROMPT[LV]());
