// 확실하지 않아 일부러 말하지 않는 것
const SILENT = [['먹이', '명사'], ['꽃잎', '명사'], ['발달', '명사'], ['물고기', '명사'], ['맛있다', '형용사'], ['협의', '명사'], ['생산량', '명사'], ['의사', '명사'], ['가다', '동사'], ['사랑', '명사'], ['알다', '동사']];
let bad = 0;
for (const [w, pos, want] of SAY) {
  if (want === null) continue;
  const g = pron(w, pos)?.s ?? null;
  if (g !== want) { bad++; console.log(`✗ ${w}: [${g}] ← [${want}] 이어야 함`); }
}
for (const [w, pos] of SILENT) { const g = pron(w, pos); if (g) { bad++; console.log(`✗ ${w}: [${g.s}] — 말하지 않아야 하는 낱말`); } }
console.log(bad ? `소리 나는 대로 검사 — 틀린 것 ${bad}개` : `소리 나는 대로 검사 — 통과 (말하는 것 ${SAY.filter((x) => x[2]).length} · 비운 것 ${SILENT.length})`);
process.exit(bad ? 1 : 0);
