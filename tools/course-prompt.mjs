/* 중급·고급 코스 레슨 지시문 뽑기.  node tools/course-prompt.mjs im-02-02
   인자 없이 돌리면 채울 코스 목록이 나온다.

   코스마다 따로 뽑는다. 한 코스의 레슨들은 같은 문법을 단계로 쌓는 것이라
   1강이 무엇을 했는지 알아야 2강을 쓸 수 있다 — 그 1강을 지시문에 통째로
   넣어 준다. 코스를 섞어 시키면 그 맥락이 끊긴다. */
import { COURSES } from '../courses.js';

const TARGET = 4;   // 코스당 레슨 수. 가장 잘 채워진 초급 코스(bg-d-02)가 셋이다.

const list = COURSES.filter((c) => c.level === 'Intermediate' || c.level === 'Advanced');
const id = process.argv[2];
const c = list.find((x) => x.id === id);
if (!c) {
  console.log('채울 코스\n');
  list.forEach((x) => console.log(
    `  ${x.id.padEnd(10)} ${x.level.padEnd(13)} 강 ${x.lessons.length} / ${TARGET}   ${x.title}`));
  console.log(`\n쓰는 법:  node tools/course-prompt.mjs ${list[0].id}`);
  process.exit(0);
}

const need = TARGET - c.lessons.length;
const nextIds = [];
for (let i = c.lessons.length + 1; i <= TARGET; i++) nextIds.push(`${c.id}-${String(i).padStart(2, '0')}`);

/* 이미 있는 레슨을 통째로 보여 준다. 제목만 주면 같은 설명을 다시 쓴다. */
const done = c.lessons.map((l, i) =>
  `### ${i + 1}강 — ${l.title}  (${l.minutes}분, 블록 ${l.blocks.length}개)\n\n` +
  l.blocks.map((b) => '  ' + JSON.stringify(b)).join('\n')
).join('\n\n');

console.log(`한국어 학습 앱의 **레슨 데이터**를 만들어 주세요.
코스 「${c.title}」에 ${need}강을 더 붙입니다.

## 이 코스가 무엇인가

  한 줄 소개   ${c.tagline}
  자세히       ${c.blurb}
  단계         ${c.level === 'Intermediate' ? '중급' : '고급'}
  앞 코스      ${c.needs}

## 이미 있는 레슨 (다시 쓰지 마세요)

${done}

## 만들 것 — ${need}강, 아래 id 를 **글자 그대로**

${nextIds.map((x, i) => `  ${c.lessons.length + i + 1}강  id: "${x}"`).join('\n')}

**id 는 한 글자도 바꾸지 마세요.** 학습자의 진도가 이 id 로만 묶여서, 나중에
바꾸면 그 레슨을 끝낸 사람의 기록이 어느 레슨에도 안 붙는 고아가 됩니다.

## 레슨 짜임 — 이 차례로 쌓아 주세요

  ${c.lessons.length + 1}강  **꼴 만들기** — 이 문법을 어떻게 붙이는가.
      받침·불규칙·품사에 따라 어떻게 갈리는지 표로 보이고 손에 익힙니다.
  ${c.lessons.length + 2}강  **헷갈리는 짝과 가르기** — 비슷해서 자꾸 섞이는 표현과 나란히 놓고
      「이때는 이것, 저때는 저것」을 상황으로 가릅니다. 1강에서 규칙을 배웠어도
      실제로 틀리는 자리가 여기입니다.
  ${c.lessons.length + 3}강  **실제 상황에서 쓰기** — 회사·집·가게에서 그대로 쓸 만한 문장으로
      직접 만들어 보게 합니다. 배운 것을 꺼내 쓰는 단계입니다.

레슨 하나에 **블록 9~12개**, \`minutes\` 는 4 또는 5.

## 블록 종류와 생김새

레슨의 \`blocks\` 는 아래 열한 가지만 씁니다. 다른 이름을 쓰면 화면이 그리지
못하고 그 레슨에서 학습자가 막힙니다.

**읽는 것**

\`\`\`json
{"t":"text","h":"무슨 말을 하는 표현인가","md":"**-고 싶다** 는 내 **마음속 바람**을 말합니다.\\n\\n일정표에 적힌 일이 아니라…"}
{"t":"note","md":"**남의 바람에는 못 씁니다.** 다른 사람이 원할 때는 **-고 싶어하다** 로 바뀝니다."}
{"t":"table","head":["사전형","어간","-고 싶어요"],"rows":[["가다 — to go","가","가**고 싶어요**"],["먹다 — to eat","먹","먹**고 싶어요**"]]}
{"t":"chars","wide":true,"items":[{"ch":"언젠가 제주도에 가고 싶어요.","tip":"I want to go to Jeju someday. — 날짜는 안 정했다"}]}
\`\`\`

- \`text\` 는 설명, \`note\` 는 곁들이는 주의. \`h\` 는 \`text\` 에만 붙입니다.
- \`md\` 안에서 \`**굵게**\` 와 줄바꿈 \`\\n\` 을 씁니다. 표를 md 안에 넣지 말고 \`table\` 블록을 쓰세요.
- \`table\` 의 **모든 \`rows\` 는 \`head\` 와 칸 수가 같아야** 합니다. 하나라도 다르면 칸이 밀립니다.
- \`chars\` 는 예문 모음. \`tip\` 에 영어 뜻과 짧은 설명을 같이 답니다.

**푸는 것**

\`\`\`json
{"t":"cloze","sentence":"나중에 세계 여행을 [가고 싶어요].","answer":"가고 싶어요","meaning":"I want to travel the world someday.",
 "options":["갈 거예요","가고 싶어요","가려고 해요","가기로 했어요"],
 "keys":["가고 싶어요","갈 거예요","가려고 해요","가기로 했어요"],
 "why":"넷 다 쓰는 말입니다. **갈 거예요** 는 일정이 잡혔다, **가려고 해요** 는 마음을 먹었다는 뜻이에요."}

{"t":"choice","q":"동생도 같이 가기를 바라고 있어요. 알맞은 것은?",
 "options":["동생도 가고 싶어요","동생도 가고 싶어해요","동생도 가려고 해요"],
 "answer":1,"why":"남의 바람을 말할 때는 -고 싶어하다 입니다."}

{"t":"type","q":"배우다 (to learn) — 「한국 요리를 ___ .」 바람으로 바꿔 쓰세요.",
 "answer":"배우고 싶어요","keys":["배우고 싶어요","배울 거예요","배우려고 해요"],
 "why":"어간 배우 에 고 싶어요 를 그대로 붙입니다."}

{"t":"order","q":"「내일 친구를 만날 거예요.」 를 만들어 보세요.",
 "tokens":["내일","친구를","만날 거예요"],"answer":["내일","친구를","만날 거예요"]}

{"t":"pair","q":"사전형과 -(으)ㄹ 거예요 형태를 짝지어 보세요.",
 "pairs":[["만나다 (받침 없음)","만날 거예요"],["읽다 (받침 ㄱ)","읽을 거예요"]]}

{"t":"speak","say":"저는 언젠가 제주도에 가서 한 달쯤 살고 싶어요.","q":"바람을 말하는 문장이라 끝을 조금 부드럽게 놓아 보세요."}
\`\`\`

## 어기면 안 되는 것 — 검사기가 잡습니다

1. **\`choice\` 의 \`answer\` 는 보기의 번호**(0부터)입니다. 글자가 아닙니다.
   보기가 셋이면 0·1·2 만 됩니다. 벗어나면 무엇을 골라도 오답이 됩니다.
2. **\`type\` 의 \`answer\` 는 반드시 \`keys\` 안에 있어야** 합니다. 한글 자판이
   없는 사람은 \`keys\` 를 눌러서 답하기 때문에, 빠지면 아예 못 풉니다.
3. **\`order\` 의 \`tokens\` 와 \`answer\` 는 같은 조각이어야** 합니다. 순서만
   다르고 조각은 똑같아야 맞출 수 있습니다.
4. **\`cloze\` 는 \`sentence\` 가 있어야** 하고, 정답 자리를 \`[대괄호]\` 로
   묶거나 \`answer\` 를 따로 적습니다. \`options\` 와 \`keys\` 에는 정답이 들어
   있어야 합니다.
5. **\`table\` 의 모든 줄은 \`head\` 와 칸 수가 같아야** 합니다.

## 글에 대한 것

- 예문은 **해요체**로 씁니다. 학습자가 그대로 쓸 말이라야 합니다.
- **한자를 쓰지 마세요.** 한글과 숫자로만.
- 영어는 \`chars\` 의 \`tip\`, \`cloze\` 의 \`meaning\`, 표의 「가다 — to go」처럼
  **뜻을 달아 주는 자리에만** 씁니다. 설명문을 영어로 쓰지 마세요.
- \`why\` 는 **왜 그것이 답인지** 를 말합니다. 나머지 보기가 왜 아닌지도
  한 조각 붙이면 좋습니다. 「정답은 2번입니다」 같은 말은 쓰지 마세요.
- ${c.level === 'Advanced'
    ? '고급이라 뉴스·사설·업무 문서처럼 격식 있는 자리의 문장을 섞어 주세요.'
    : '중급이라 회사·가게·이웃처럼 일상에서 겪는 상황으로 씁니다.'}

## 출력 형식

마크다운 울타리 없이 **JSON 배열 하나만** 주세요. 레슨 ${need}개입니다.

\`\`\`
[
  { "id": "${nextIds[0]}", "title": "${c.lessons.length + 1}강. …", "minutes": 4, "blocks": [ … ] },
  …
]
\`\`\`

## 다 만든 뒤 확인할 것

- [ ] 레슨이 ${need}개인가, id 가 ${nextIds.join(' · ')} 인가
- [ ] 레슨마다 블록이 9~12개인가
- [ ] \`choice\` 의 answer 가 전부 보기 번호(0부터)인가
- [ ] \`type\` 의 answer 가 전부 keys 안에 있는가
- [ ] \`order\` 의 tokens 와 answer 가 같은 조각인가
- [ ] \`table\` 의 모든 줄 칸 수가 head 와 같은가
- [ ] 이미 있는 1강과 설명·예문이 겹치지 않는가
- [ ] 한자가 없는가`);
