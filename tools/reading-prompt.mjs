#!/usr/bin/env node
/* 읽기 연습 지문을 더 만들기 위한 지시문을 뽑는다.

   쓰기: node tools/reading-prompt.mjs short beginner
         node tools/reading-prompt.mjs long advanced

   길이와 급수를 한 판에 하나씩만 시킨다. 여섯 칸을 한 번에 시키면 모델이
   길이 기준을 섞는다 — 발음 지문에서 실제로 그랬다.

   지금 있는 것을 지시문 안에 통째로 넣는다. 「이런 느낌으로」라고 말로
   설명하는 것보다 실물 하나를 보여 주는 쪽이 훨씬 잘 맞는다. */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { READING } = await import(pathToFileURL(path.join(ROOT, 'reading.js')).href);

const [LEN, LV, N] = process.argv.slice(2);
/* 여섯 칸이라 칸마다 여덟 편이면 마흔여덟 편이 된다. 한 판에 더 시킬
   수도 있지만, 긴 글은 한 편이 500자라 한 번에 많이 시키면 뒤로 갈수록
   짧아지고 소재가 겹친다 — 발음 지문에서 실제로 그랬다. */
const HOW_MANY = Math.max(1, Math.min(30, parseInt(N, 10) || 8));

const BAND = {
  short: { 자: '60자 이상 200자 이하', 문장: '3~5문장', 답: '2~4문장', keys: '3~4개',
           결: '짬이 날 때 한 편 읽는 분량이다.' },
  long:  { 자: '280자 이상 520자 이하', 문장: '8~12문장', 답: '3~6문장', keys: '3~5개',
           결: '자리를 잡고 한 편 읽는 분량이다. 문단 하나로 이어져야 하고, 앞뒤가 논리로 이어져야 한다.' },
};

const LEVEL = {
  beginner: `**초급 (TOPIK 1~2급 정도)**

* 「-습니다 / -아요·어요」 만 쓴다. 반말·하오체·해라체를 섞지 마라.
* 문법은 기본만 — 과거(-았/었-), 이유(-아서), 나열(-고), 희망(-고 싶다),
  능력(-을 수 있다) 정도까지. -더니, -는 바람에, -기 마련이다 같은 것은 쓰지 마라.
* 낱말은 일상어. 집·밥·학교·회사·날씨·가족·주말·물건 사기 같은 자리.
* 한자어 전문 용어, 추상적인 말(사회·인식·경향·구조)은 쓰지 마라.
* 글쓴이의 의견을 묻지 마라. **무슨 일이 있었는지**를 다시 말하게 한다.`,

  intermediate: `**중급 (TOPIK 3~4급 정도)**

* 「-습니다 / -아요·어요」 를 쓰되, 설명하는 글이라 -ㄴ다고 합니다 · -다는
  같은 인용과 관형형이 자연스럽게 섞인다.
* 문법은 -기 때문에, -는 편이다, -자마자, -는데, -더라도, -을수록 정도까지.
* 소재는 생활 속의 설명거리 — 습관, 건강, 계절, 도시와 시골, 일하는 방식,
  사람들이 흔히 하는 오해 같은 것.
* 한 편에 **주장 하나**만 담아라. 두 가지를 같이 말하면 요약이 흐려진다.
* 질문은 「무엇을 말하는지 정리해 보세요」 쪽이다. 의견까지 묻지는 않는다.`,

  advanced: `**고급 (TOPIK 5~6급 정도)**

* 칼럼이나 사설의 말투. 「-습니다」체로 쓰되 문장이 길고 짜임이 있다.
* 문법은 -는 셈이다, -기 마련이다, -을 뿐 아니라, -는다는 점에서,
  -에 지나지 않는다, -기는커녕 같은 것까지 써도 된다.
* **주장이 있어야 한다.** 사실만 늘어놓은 글은 고급이 아니다. 흔한 통념을
  하나 세우고 그것을 뒤집거나 반만 맞다고 하는 짜임이 좋다.
* 소재는 시간이 지나도 안 낡는 것으로. 정치·시사·특정 인물·특정 회사·
  통계 수치의 출처가 필요한 이야기는 쓰지 마라.
* 질문은 「주장을 정리하고 자기 생각을 쓰세요」 쪽이다.`,
};

if (!BAND[LEN] || !LEVEL[LV]) {
  console.error('쓰기: node tools/reading-prompt.mjs short|long beginner|intermediate|advanced');
  process.exit(1);
}

const have = READING[LEN][LV];
const sample = have[0] ?? READING.short.beginner[0];
const idHead = `r${LEN[0]}-${LV[0]}-`;
const nextNo = have.length + 1;

console.log(`너는 한국어 읽기 교재를 만드는 사람이다. 한국어를 배우는 외국인이
**읽고, 이해한 것을 자기 말로 다시 써 보는** 연습 지문을 만든다.

읽고 보기에서 고르는 문제가 아니다. 읽은 다음 **빈 칸에 직접 쓰는** 자리다.
그래서 지문은 「다시 말할 거리가 있는 글」이어야 한다. 아무 일도 일어나지
않거나 요약할 것이 없는 글은 쓸모가 없다.

## 채점이 어떻게 되는지 — 이걸 알아야 keys 를 제대로 쓴다

학습자가 쓴 글에서 keys 의 낱말을 찾아 몇 개를 짚었는지로 점수를 낸다.
그래서 keys 는 이렇게 만들어야 한다.

* 각 항목의 \`k\` 는 **인정할 말들의 배열**이다. 같은 것을 가리키는 다른
  말을 함께 적어라 — 「지하철」이면 「전철」도, 「경쟁」이면 「겨루」도.
  이걸 안 하면 맞게 쓴 학습자가 점수를 못 받는다.
* \`k\` 의 낱말은 **두 글자 이상**이어야 한다. 「물」 같은 한 글자는 아무
  글에나 들어 있어서 점수를 못 가른다. 「물을」처럼 늘려라.
* 한 낱말이 **두 항목에 겹치면 안 된다.** 한 낱말이 두 점을 준다.
* \`k\` 중 적어도 하나는 **모범 답안(model)에 반드시 들어 있어야 한다.**
  본보기가 만점을 못 받으면 학습자에게 보여 줄 낯이 없다.
* \`why\` 는 그것이 왜 짚을 거리인지 짧게. 학습자에게 그대로 보여 준다.

## 이번에 만들 것 — ${LEN === 'short' ? '짧은 글' : '긴 글'} · ${LV === 'beginner' ? '초급' : LV === 'intermediate' ? '중급' : '고급'} ${HOW_MANY}편

### 길이
* 지문은 **${BAND[LEN].자}**, **${BAND[LEN].문장}**. ${BAND[LEN].결}
* 모범 답안(model)은 **${BAND[LEN].답}**.
* 짚을 거리(keys)는 **${BAND[LEN].keys}**.

### 급수
${LEVEL[LV]}

### 모든 편에 공통으로

1. **en 은 지문을 통째로 옮긴 영어다.** 요약이 아니다. 학습자가 다 쓰고 나서
   「내가 맞게 읽었나」를 대조하는 자리라, 문장 수도 지문과 같아야 한다.
   자연스러운 영어로 옮겨라 — 낱말을 하나씩 바꾼 번역투는 대조에 쓸모가 없다.
2. **words 는 지문에서 막힐 만한 낱말 3~4개**와 그 영어 뜻이다. 반드시
   그 지문 안에 나오는 말이어야 한다. 사전형(-다)으로 적어라.
3. 시사·정치·종교·질병·사고·특정 인물·특정 회사·출처가 필요한 통계는 쓰지 마라.
4. 지문 안에 따옴표(" ')를 쓰지 마라. 필요하면 「 」를 써라.
5. 여덟 편의 소재가 서로 겹치지 않게 해라.

## 지금 있는 것 — 이 짜임과 치수를 그대로 맞춰라

\`\`\`json
${JSON.stringify(sample, null, 2)}
\`\`\`
${have.length > 1 ? `\n이 칸에는 이미 ${have.length}편이 있다. 제목이 겹치지 않게 해라 — ${have.map((r) => r.title).join(' · ')}\n` : ''}
## 내놓는 방법

JSON 배열 하나로만 답해라. 설명·머리말·번호를 붙이지 마라.
id 는 \`${idHead}${String(nextNo).padStart(2, '0')}\` 부터 하나씩 올려라.

\`\`\`json
[
  { "id": "${idHead}${String(nextNo).padStart(2, '0')}", "title": "…", "passage": "…", "en": "…",
    "question": "…", "model": "…",
    "keys": [{ "k": ["…", "…"], "why": "…" }],
    "words": [["…다", "…"]] }
]
\`\`\`

정확히 **${HOW_MANY}편**을 담아라.`);
