#!/usr/bin/env node
/* 문법 검사기 — node tools/check-grammar.mjs
 *
 * 맞춤법은 글자가 틀린 것이고, 문법은 **문장이 어긋난 것이다.** 글자는 다
 * 맞는데 문장이 성립하지 않는 일이 있다.
 *
 *     왜냐하면 비가 왔다.          「왜냐하면」을 열어 놓고 안 닫았다
 *     결코 그렇다.                「결코」는 부정하고만 짝을 짓는다
 *     이 문제는 잘 해결되어졌다.    피동을 두 번 걸었다
 *
 * 이런 것은 눈으로 잘 안 잡힌다. 한 문장 안에서 **앞과 뒤가 멀기** 때문이다.
 * 「왜냐하면」을 읽을 때는 뒤를 모르고, 끝에 닿을 때는 앞을 잊는다. 사람이
 * 못 하는 일이고 기계가 잘하는 일이다.
 *
 * 여기서 보는 것은 짝이 정해진 것들뿐이다. **말이 자연스러운지는 안 본다.**
 * 그것은 기계가 판정할 것이 아니고, 어설프게 판정하면 멀쩡한 문장을 고치라고
 * 한다.
 *
 *   node tools/check-grammar.mjs            넘어가기로 적어 둔 것은 빼고
 *   node tools/check-grammar.mjs --all      전부
 *   node tools/check-grammar.mjs --accept   지금 나온 것을 넘어가기로
 */
import { loadCorpus, sentences, quotedSpans, inSpans } from './lib/corpus.mjs';
import { Lint } from './lib/lint.mjs';

const lint = new Lint('문법');
const corpus = await loadCorpus();

/* 가르치려고 일부러 늘어놓은 글은 문장으로 안 센다.
   「「먹습니다」와 「먹어요」」처럼 보기를 나란히 든 줄이 그렇다. */
const TEACHING = /[ㄱ-ㆎ]|\*\*|[·/]|_{2,}|[①-⑳]|→/;

/* 영어 설명문 안에도 우리 말이 낱말로 박혀 있다.
 *
 *     Adding 「만약」 at the front makes it feel more hypothetical.
 *
 * 이것을 한국어 문장으로 세면 「만약을 열어 놓고 -면을 안 닫았다」고 한다.
 * 한글보다 로마자가 많으면 한국어 문장이 아니다. */
const isKorean = (s) => (s.match(/[가-힣]/g) || []).length > (s.match(/[A-Za-z]/g) || []).length;

/* ── 1. 짝이 정해진 것 ───────────────────────────────────────────────
 *
 * 앞에 이 말이 나오면 뒤에 반드시 저 말이 와야 한다. 안 오면 문장이
 * 끝나지 않은 것이다. 이것은 취향이 아니라 짝이다.
 */
/* 부정을 나타내는 꼬리.
 *
 * **어간만 적으면 안 된다.** 한국어는 활용하면서 글자가 바뀐다.
 *
 *     아니다 → 아닙니다     「아니」라는 글자가 없다. 아·닙·니·다 다
 *     모르다 → 몰라요       「모르」가 없다
 *     말다   → 마세요       「말」이 없다
 *     다르다 → 다릅니다     「다르」가 없다
 *
 * 처음에 「아니」만 적어 두고 「전혀 아닙니다」를 잘못이라고 짚었다. 글자
 * 단위로 보는 검사기에서 늘 이것부터 틀린다. */
const NEG = /않|없|못|아니|아닙|아냐|아녜|말[것고자]|마세요|마십시오|마라|맙시|모르|몰라|몰랐|모릅/;

const PAIRS = [
  { head: /왜냐하면/, tail: /때문|까닭|이라서|어서다|거든|는 것이다|은 것이다/, name: '왜냐하면 ~ 때문이다/-거든요' },
  { head: /비록/, tail: /지만|더라도|라도|어도|아도|나마/, name: '비록 ~ -지만/-더라도' },
  /* 「만약의 사태」의 만약은 명사다. 뒤에 조사가 붙으면 접속부사가 아니다 */
  { head: /만약(?![의이은는을에])|만일(?![의이은는을에])/, tail: /면|거든|라면|다면/, name: '만약 ~ -면' },
  /* 「-아도/-어도」는 줄어들면 글자가 남지 않는다 — 바쁘+아도는 「바빠도」,
     하+여도는 「해도」다. 그래서 어미가 아니라 **끝소리 「도」**로 본다 */
  { head: /아무리/, tail: /도(?![가-힣])|라도|더라도|든|기로서니|래야|려야|한들/, name: '아무리 ~ -아도/-어도' },
  /* 「차라리」는 짝이 느슨하다. 「차라리 걸어서 가요」도 멀쩡한 문장이라
     짝을 물을 수가 없다. 짝이 정해진 것만 여기 둔다. */
  { head: /여간/, tail: /않|아니|없/, name: '여간 ~ 않다 (「여간」은 부정과만 짝짓는다)' },
  /* 「말다」는 「마세요」·「마라」·「맙시다」로 활용되어 「말」이 안 남는다 */
  { head: /결코|절대로|도무지|당최/, tail: NEG, name: '결코·절대로 ~ 부정' },
  /* 「전혀」는 부정 말고 「전혀 다르다」·「전혀 새롭다」와도 짝을 짓는다.
     사전에 그렇게 실려 있다 — 부정만 짝이라고 보면 멀쩡한 문장을 잡는다 */
  { head: /전혀/, tail: new RegExp(NEG.source + '|다르|다릅|달라|달랐|딴|새로|생소|반대'), name: '전혀 ~ 부정' },
  { head: /하물며/, tail: /랴|겠는가|일까|겠나/, name: '하물며 ~ -겠는가' },
];

for (const r of corpus) {
  if (r.word || TEACHING.test(r.text)) continue;
  for (const s of sentences(r.text)) {
    if (s.length < 6 || !isKorean(s)) continue;
    /* 「전혀. 또는 도무지.」 같은 뜻풀이 조각은 문장이 아니다 —
       짝을 따질 앞뒤가 아예 없다 */
    if ((s.match(/\S+/g) || []).length < 4) continue;
    const spans = quotedSpans(s);
    for (const p of PAIRS) {
      const m = p.head.exec(s);
      p.head.lastIndex = 0;
      if (!m || p.tail.test(s)) continue;
      /* 낫표 안에 든 것은 말을 하는 것이 아니라 그 말을 가리키는 것이다 —
         「앞에 「아무리」와 짝을 이룹니다」 */
      if (inSpans(spans, m.index)) continue;
      lint.add('짝이 안 맞는다', 'bad', r, {
        found: m[0], want: null,
        why: `${p.name} — 앞말을 열어 놓고 뒤를 안 닫았다`,
      });
    }
  }
}

/* ── 2. 이중 피동 ────────────────────────────────────────────────────
 *
 * 「보다」를 피동으로 만들면 「보이다」다. 거기에 「-어지다」를 또 걸면
 * 「보여지다」가 되는데, 피동을 두 번 건 것이라 문법에 안 맞는다. 뜻도
 * 안 는다 — 그냥 「보이다」다.
 *
 * 흔히 쓰인다고 맞는 것은 아니지만, **학습 자료에서는 특히 안 된다.**
 * 배우는 사람은 여기서 본 꼴을 그대로 외운다.
 */
const DOUBLE_PASSIVE = [
  '보여지', '보여진', '쓰여지', '불려지', '잊혀지', '나뉘어지', '짜여지',
  '닫혀지', '열려지', '걸려지', '끊겨지', '믿겨지', '놓여지', '덮여지',
  '모여지', '읽혀지', '들려지', '잘려지', '꺾여지', '되어지', '되어진', '되어졌',
];
const PASSIVE_FIX = {
  보여지: '보이', 보여진: '보인', 쓰여지: '쓰이', 불려지: '불리', 잊혀지: '잊히',
  나뉘어지: '나뉘', 짜여지: '짜이', 닫혀지: '닫히', 열려지: '열리', 걸려지: '걸리',
  끊겨지: '끊기', 믿겨지: '믿기', 놓여지: '놓이', 덮여지: '덮이', 모여지: '모이',
  읽혀지: '읽히', 들려지: '들리', 잘려지: '잘리', 꺾여지: '꺾이',
  되어지: '되', 되어진: '된', 되어졌: '됐',
};
for (const r of corpus) {
  for (const w of DOUBLE_PASSIVE) {
    if (!r.text.includes(w)) continue;
    lint.add('이중 피동', 'bad', r, {
      found: w, want: PASSIVE_FIX[w],
      why: '피동을 두 번 걸었다 — 한 번이면 된다',
    });
  }
}

/* ── 3. 조사 겹침은 여기서 안 본다 ─────────────────────────────────
 *
 * 「에에」·「을을」·「가가」처럼 조사가 두 번 붙은 것을 잡으려 했다. 돌려
 * 보니 43건이 나왔고 **전부 멀쩡한 말이었다.**
 *
 *     물가가    물가(物價) + 가        「물+가가」가 아니다
 *     통로로    통로(通路) + 로        「통+로로」가 아니다
 *     마을을    마을 + 을
 *     의의      의의(意義) 라는 낱말이다
 *
 * 낱말이 조사와 같은 글자로 끝나는 일이 흔해서, 글자만 보고는 「겹쳐 붙은
 * 것」과 「그렇게 끝나는 낱말」을 가를 수 없다. 가르려면 형태소 분석기가
 * 있어야 하고, 그것은 이 저장소가 들일 것이 아니다.
 *
 * **못 가르는 것은 안 잡는 편이 낫다.** 남겨 둔다, 다시 넣지 않도록.
 */

/* ── 4. 한 문장 안에서 말투가 갈린다 ────────────────────────────────
 *
 * 「-습니다」와 「-어요」는 둘 다 존댓말이지만 자리가 다르다. 한 문장 안에서
 * 갈리면 배우는 사람이 어느 쪽을 따라야 할지 모른다.
 *
 * 이것은 **틀렸다고 못 박을 것이 아니다.** 인용이나 대조로 일부러 섞는
 * 자리가 있다. 짚어만 둔다.
 */
for (const r of corpus) {
  if (r.word || TEACHING.test(r.text) || /[「『"']/.test(r.text)) continue;
  for (const s of sentences(r.text)) {
    const formal = /(습니다|ㅂ니다|십시오|습니까)/.test(s);
    const polite = /(아요|어요|예요|이에요|세요|에요)[.!?]?$/.test(s);
    if (formal && polite) {
      lint.add('한 문장에 말투가 둘', 'warn', r, {
        found: s.slice(0, 40), want: null,
        why: '「-습니다」와 「-어요」가 한 문장에 같이 있다 — 배우는 사람이 어느 쪽을 따를지 모른다',
      });
    }
  }
}

/* ── 5. 「-의」를 잇달아 쓴 것 ──────────────────────────────────────
   일본말과 번역글의 버릇이다. 「나의 친구의 집의 마당」처럼 이어지면 우리
   말로는 읽기 어렵다. 셋 이상일 때만 짚는다. */
for (const r of corpus) {
  /* 한 문장에 「-의」가 여럿인 것은 흠이 아니다. 서로 다른 자리에 하나씩
     붙은 것뿐일 수 있다. 흠이 되는 것은 **잇달아 매달린 것**이다 —
     「나의 친구의 집의 마당」. 낱말 두 개 안에서 두 번 나오는 것만 본다. */
  for (const s of sentences(r.text)) {
    const m = s.match(/[가-힣]+의\s+[가-힣]+의\s+[가-힣]+의/);
    if (m) {
      lint.add('「-의」가 잇달았다', 'warn', r, {
        found: m[0], want: null,
        why: '「-의」가 셋 잇달아 매달렸다 — 번역글의 버릇이다. 하나는 덜어 낼 수 있다',
      });
    }
  }
}

const chars = corpus.reduce((a, r) => a + r.text.length, 0);
process.exit(lint.report(`글 조각 ${corpus.length.toLocaleString()}개 · ${chars.toLocaleString()}자를 봤다.`));
